// TODO: It is perfectly possible to convert the following test into compile time checks.
// We take care of that later.
#[cfg(test)]
mod tests {
    use super::super::msr_based_features::INTEL_MSR_FEATURE_DEFINITIONS;
    use super::super::{FORBIDDEN_IA32_MSR_RANGES, PERMITTED_IA32_MSRS};
    use super::NON_ARCHITECTURAL_INTEL_MSRS;
    #[test]
    fn print_unique() {
        let mut unique_count = 0;
        for msr in NON_ARCHITECTURAL_INTEL_MSRS {
            if (!PERMITTED_IA32_MSRS.contains(&msr))
                && (!FORBIDDEN_IA32_MSR_RANGES
                    .iter()
                    .any(|r| (r.0..=r.1).contains(&msr)))
                && (!INTEL_MSR_FEATURE_DEFINITIONS
                    .as_slice()
                    .iter()
                    .any(|(address, _)| address.0 == msr))
            {
                unique_count += 1;
            }
        }
        assert_eq!(unique_count, NON_ARCHITECTURAL_INTEL_MSRS.len());
    }
}
